def src(q):
    y, n = int(q[:4]), int(q[-1])
    if (y, n) <= (2019, 3): return SOURCES["8K_2019"]
    if y <= 2024: return SOURCES[f"Q4_{str(max(y,2020))[2:]}"]
    return SOURCES["Q4_25"] if (y, n) <= (2025, 1) else SOURCES["Q2_26"]

rows = []
for r in ["UCAN", "EMEA", "LATAM", "APAC"]:
    for i, (rev, mem, add, arm) in enumerate(EARLY[r]):
        q = QS[i]; rows.append([r, q, round(rev/1000, 3), round(mem/1000, 3), round(add/1000, 3), arm, "", src(q)])
    for i, (rev, mem, add, arm, fx) in enumerate(LATE[r]):
        q = QS[11+i]; rows.append([r, q, rev, mem, add, arm, fx, src(q)])
    for i, rev in enumerate(REV_ONLY[r]):
        q = QS[32+i]; rows.append([r, q, rev, "", "", "", "", src(q)])
